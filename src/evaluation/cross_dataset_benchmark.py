"""
Cross-dataset benchmark for the unified evaluation dataset.

Primary use:
- Train on Empirical-Analysis (clean vs vulnerable)
- Test on FORGE (severity-derived negatives)

Inputs (generated by existing modules):
- data/derived/unified_contract_eval_scored.csv

Outputs:
- data/derived/unified_labels_clean.csv
- data/derived/unified_labels_clean_summary.csv
- data/derived/cross_dataset_empirical_to_forge_results.csv

Run:
  python3 -m src.evaluation.cross_dataset_benchmark
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import ExtraTreesClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.pipeline import Pipeline


def _is_addr(s: object) -> bool:
    return isinstance(s, str) and s.startswith("0x") and len(s) == 42


def _norm_addr(s: object) -> str:
    return str(s or "").strip().lower()


class CrossDatasetBenchmark:
    def __init__(
        self,
        *,
        scored_csv: Path = Path("data/derived/unified_contract_eval_scored.csv"),
        out_dir: Path = Path("data/derived"),
    ) -> None:
        logger = logging.getLogger("cross_dataset_benchmark")
        logger.setLevel(logging.INFO)
        if not logger.handlers:
            h = logging.StreamHandler()
            h.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(name)s: %(message)s"))
            logger.addHandler(h)
        self.logger = logger
        self.scored_csv = Path(scored_csv)
        self.out_dir = Path(out_dir)

    def build_clean_labels(self) -> Path:
        """
        Create address-level gold labels for Empirical and FORGE.

        Empirical:
          - label_status clean => 0
          - label_status vulnerable => 1

        FORGE:
          - vuln_severity in {medium,high,critical} => 1
          - vuln_severity in {info,low} => 0
          - otherwise => drop (unknown)
        """
        try:
            df = pd.read_csv(self.scored_csv)
            df["address"] = df["address"].map(_norm_addr)
            df = df[df["address"].map(_is_addr)].copy()

            df["source_dataset"] = df["source_dataset"].fillna("").astype(str)
            df["label_status"] = df["label_status"].fillna("").astype(str).str.lower()
            df["vuln_severity"] = df["vuln_severity"].fillna("").astype(str).str.lower()

            def forge_gold(sev: str) -> float:
                if sev in {"critical", "high", "medium"}:
                    return 1.0
                if sev in {"low", "info"}:
                    return 0.0
                return float("nan")

            def empirical_gold(ls: str) -> float:
                if ls == "vulnerable":
                    return 1.0
                if ls == "clean":
                    return 0.0
                return float("nan")

            df["y_gold"] = np.nan
            is_emp = df["source_dataset"] == "Empirical-Analysis"
            is_forge = df["source_dataset"] == "FORGE"
            df.loc[is_emp, "y_gold"] = df.loc[is_emp, "label_status"].map(empirical_gold)
            df.loc[is_forge, "y_gold"] = df.loc[is_forge, "vuln_severity"].map(forge_gold)

            df = df[df["source_dataset"].isin(["Empirical-Analysis", "FORGE"])].copy()

            agg = (
                df.groupby(["source_dataset", "address"], as_index=False)
                .agg(
                    y_gold_min=("y_gold", "min"),
                    y_gold_max=("y_gold", "max"),
                    n_rows=("contract_id", "count"),
                    label_status_any=("label_status", lambda s: ";".join(sorted(set([str(x) for x in s if str(x)])))[:200]),
                    vuln_severity_any=("vuln_severity", lambda s: ";".join(sorted(set([str(x) for x in s if str(x)])))[:200]),
                )
                .copy()
            )

            valid = agg["y_gold_min"].notna() & agg["y_gold_max"].notna() & (agg["y_gold_min"] == agg["y_gold_max"])
            labels = agg[valid].copy()
            labels["y_gold"] = labels["y_gold_min"].astype(int)
            labels.drop(columns=["y_gold_min", "y_gold_max"], inplace=True)

            self.out_dir.mkdir(parents=True, exist_ok=True)
            out_labels = self.out_dir / "unified_labels_clean.csv"
            out_labels_summary = self.out_dir / "unified_labels_clean_summary.csv"
            labels.to_csv(out_labels, index=False)

            summary = (
                labels.groupby("source_dataset")
                .agg(
                    addresses=("address", "nunique"),
                    pos=("y_gold", "sum"),
                    neg=("y_gold", lambda s: int((s == 0).sum())),
                )
                .reset_index()
            )
            summary["pos_rate"] = summary["pos"] / summary["addresses"]
            summary.to_csv(out_labels_summary, index=False)

            self.logger.info(f"Wrote: {out_labels}")
            self.logger.info(f"Wrote: {out_labels_summary}")
            return out_labels
        except Exception as e:
            self.logger.error(f"Exception {e} occurred during build_clean_labels", exc_info=True)
            raise

    def run(self) -> Path:
        """
        Train on Empirical-Analysis (clean vs vulnerable), test on FORGE (severity-derived negatives).
        Writes `cross_dataset_empirical_to_forge_results.csv`.
        """
        try:
            if not self.scored_csv.exists():
                raise FileNotFoundError(f"Missing input scored CSV: {self.scored_csv}")

            out_labels = self.build_clean_labels()

            sc = pd.read_csv(self.scored_csv)
            sc["address"] = sc["address"].map(_norm_addr)
            sc = sc[sc["address"].map(_is_addr)].copy()

            labels = pd.read_csv(out_labels)
            labels["address"] = labels["address"].map(_norm_addr)

            # feature selection (numeric, exclude IDs/labels/paths + exclude risk_* outputs)
            exclude_cols = {
                "row_id",
                "contract_id",
                "address",
                "chain",
                "source_dataset",
                "source_subdataset",
                "label_status",
                "vuln_present",
                "vuln_types",
                "vuln_severity",
                "compiler_version",
                "implementation_address",
                "local_source_path",
                "local_bytecode_path",
                "local_metadata_path",
                "has_risk_row",
            }
            feat_cols: list[str] = []
            for c in sc.columns:
                if c in exclude_cols or str(c).startswith("risk_"):
                    continue
                s = pd.to_numeric(sc[c], errors="coerce")
                if float(s.notna().mean()) >= 0.8:
                    feat_cols.append(c)
            if not feat_cols:
                raise ValueError("No usable numeric features found for benchmark.")

            # activity vs code heuristic split
            activity_cols = [
                c
                for c in feat_cols
                if (
                    c.startswith("tx_")
                    or c.endswith("_30d")
                    or c.endswith("_90d")
                    or c.endswith("_365d")
                    or c
                    in {
                        "age_days",
                        "last_tx_age_days",
                        "failed_tx_rate_90d",
                        "admin_event_churn_365d",
                        "has_activity_payload",
                        "value_in_eth_30d",
                        "value_out_eth_30d",
                    }
                )
            ]
            for c in [
                "erc20_tx_count_30d",
                "erc20_unique_tokens_30d",
                "erc20_unique_senders_30d",
                "erc20_unique_receivers_30d",
                "internal_tx_count_30d",
                "unique_senders_30d",
            ]:
                if c in feat_cols and c not in activity_cols:
                    activity_cols.append(c)
            code_cols = [c for c in feat_cols if c not in activity_cols]

            for c in feat_cols + ["risk_z", "risk_raw"]:
                if c in sc.columns:
                    sc[c] = pd.to_numeric(sc[c], errors="coerce")

            agg = sc.groupby(["source_dataset", "address"], as_index=False).agg(
                {**{c: "mean" for c in feat_cols}, "risk_z": "mean", "risk_raw": "mean"}
            )
            data = labels.merge(agg, on=["source_dataset", "address"], how="left")

            train = data[data["source_dataset"] == "Empirical-Analysis"].dropna(subset=feat_cols).copy()
            test = data[data["source_dataset"] == "FORGE"].dropna(subset=feat_cols).copy()
            if train.empty or test.empty:
                raise ValueError(f"Empty train or test split. train_rows={len(train)}, test_rows={len(test)}")

            Xtr_all = train[feat_cols]
            Xte_all = test[feat_cols]
            Xtr_code = train[code_cols]
            Xte_code = test[code_cols]
            Xtr_act = train[activity_cols]
            Xte_act = test[activity_cols]
            ytr = train["y_gold"].astype(int).to_numpy()
            yte = test["y_gold"].astype(int).to_numpy()

            # tuned tree (from earlier GroupKFold tuning on Empirical)
            tuned_et = ExtraTreesClassifier(
                n_estimators=600,
                max_depth=24,
                min_samples_leaf=3,
                min_samples_split=10,
                max_features=0.6,
                random_state=42,
                n_jobs=-1,
                class_weight="balanced_subsample",
            )

            models: dict[str, object] = {
                "baseline_risk_z": None,
                "baseline_risk_raw": None,
                "logreg_all": Pipeline(
                    [
                        ("impute", SimpleImputer(strategy="median")),
                        ("clf", LogisticRegression(max_iter=4000, solver="liblinear", class_weight="balanced")),
                    ]
                ),
                "extratrees_all": Pipeline([("impute", SimpleImputer(strategy="median")), ("clf", tuned_et)]),
                "extratrees_code_only": Pipeline([("impute", SimpleImputer(strategy="median")), ("clf", tuned_et)]),
                "extratrees_activity_only": Pipeline([("impute", SimpleImputer(strategy="median")), ("clf", tuned_et)]),
            }

            def metrics(y: np.ndarray, s: np.ndarray) -> dict[str, float]:
                return {
                    "roc_auc": float(roc_auc_score(y, s)),
                    "pr_auc": float(average_precision_score(y, s)),
                }

            preds: dict[str, np.ndarray] = {
                "baseline_risk_z": test["risk_z"].to_numpy(),
                "baseline_risk_raw": test["risk_raw"].to_numpy(),
            }

            models["logreg_all"].fit(Xtr_all, ytr)
            preds["logreg_all"] = models["logreg_all"].predict_proba(Xte_all)[:, 1]

            models["extratrees_all"].fit(Xtr_all, ytr)
            preds["extratrees_all"] = models["extratrees_all"].predict_proba(Xte_all)[:, 1]

            models["extratrees_code_only"].fit(Xtr_code, ytr)
            preds["extratrees_code_only"] = models["extratrees_code_only"].predict_proba(Xte_code)[:, 1]

            models["extratrees_activity_only"].fit(Xtr_act, ytr)
            preds["extratrees_activity_only"] = models["extratrees_activity_only"].predict_proba(Xte_act)[:, 1]

            rows = []
            for name, s in preds.items():
                m = metrics(yte, s)
                rows.append(
                    {
                        "model": name,
                        "train_dataset": "Empirical-Analysis",
                        "test_dataset": "FORGE",
                        "train_addresses": int(train["address"].nunique()),
                        "test_addresses": int(test["address"].nunique()),
                        "train_pos_rate": float(train["y_gold"].mean()),
                        "test_pos_rate": float(test["y_gold"].mean()),
                        **m,
                    }
                )

            out = pd.DataFrame(rows).sort_values(["pr_auc", "roc_auc"], ascending=False)
            out_path = self.out_dir / "cross_dataset_empirical_to_forge_results.csv"
            out.to_csv(out_path, index=False)
            self.logger.info(f"Wrote: {out_path}")
            return out_path
        except Exception as e:
            self.logger.error(f"Exception {e} occurred during run", exc_info=True)
            raise


def main() -> None:
    CrossDatasetBenchmark().run()


if __name__ == "__main__":
    main()

